'use strict';
const path=require('path');
const mem=new Map();
global.localStorage={getItem:k=>mem.has(k)?mem.get(k):null,setItem:(k,v)=>mem.set(k,String(v)),removeItem:k=>mem.delete(k),key:i=>[...mem.keys()][i]||null,get length(){return mem.size}};
const ResearchData=require(path.resolve(__dirname,'../research-data.js'));
let pass=0,fail=0;const check=(name,cond,detail='')=>{if(cond){pass++;console.log('  ✅ '+name)}else{fail++;console.log('  ❌ '+name+(detail?' — '+detail:''))}};
console.log('=== Research Data Model v1 ===');
ResearchData._clear();
check('model version explicit',ResearchData.MODEL_VERSION==='research-data-model-1.0.0');
const cfg=ResearchData.configureStudy({studyId:'STUDY-A',siteId:'SITE-TOKYO',consentVersion:'consent-v1',operatorId:'ignored'});
check('study configured',cfg.study.id==='STUDY-A');
check('site configured',cfg.site.id==='SITE-TOKYO');
check('consent version stored',cfg.study.consentVersion==='consent-v1');
const p=ResearchData.ensureParticipant('P001',{siteId:'SITE-TOKYO'});
check('participant linked to study',p.studyId==='STUDY-A');
check('participant linked to site',p.siteId==='SITE-TOKYO');
const s=ResearchData.beginSession('P001',{siteId:'SITE-TOKYO',operatorId:'OP-1',build:{id:'build-abc',commit:'abc',protocolManifest:{manifestHash:'m1',protocolLockHash:'p1'}}});
check('session created',/^session-/.test(s.id));
check('session active',s.status==='active');
check('session linked participant',s.participantId==='P001');
check('session captures operator',s.operatorId==='OP-1');
check('session captures manifest fingerprints',s.protocolManifest&&s.protocolManifest.manifestHash==='m1'&&s.protocolManifest.protocolLockHash==='p1');
const same=ResearchData.beginSession('P001',{siteId:'SITE-TOKYO'});
check('beginSession reuses active session',same.id===s.id);
const updated=ResearchData.updateSession(s.id,{environment:{browser:'Chromium',viewport:{width:1280,height:720}}});
check('environment persisted',updated.environment&&updated.environment.browser==='Chromium');
const a=ResearchData.recordAttempt({sessionId:s.id,participantId:'P001',testKey:'tmt',taskVersion:'tmt-web-0.4.0',protocolId:'trail-making-browser-synthetic-v2',qcStatus:'valid'});
check('attempt linked to session',a.sessionId===s.id);
check('attempt captures protocol identity',a.testKey==='tmt'&&a.taskVersion==='tmt-web-0.4.0'&&a.protocolId==='trail-making-browser-synthetic-v2');
const closed=ResearchData.closeSession(s.id,{status:'completed'});
check('session closes',closed.status==='completed'&&!!closed.completedAt);
const s2=ResearchData.beginSession('P001',{siteId:'SITE-TOKYO'});
check('new session after close',s2.id!==s.id);
const snap=ResearchData.snapshot();
check('snapshot has study/site/participant/session/attempt layers',snap.study&&snap.sites['SITE-TOKYO']&&snap.participants.P001&&Object.keys(snap.sessions).length===2&&snap.attempts.length===1);
check('audit trail populated',snap.audit.length>=7);
const bundle=ResearchData.exportBundle({participantData:{schemaVersion:4,participants:{P001:{}}}});
check('export bundle format explicit',bundle.format==='psy-exp-research-data-bundle');
check('export includes participant payload',bundle.participantData&&bundle.participantData.participants.P001);
check('export includes research metadata',bundle.researchData.modelVersion===ResearchData.MODEL_VERSION);
console.log(`\n=== Result: ${pass} passed / ${fail} failed ===`);process.exit(fail===0?0:1);
