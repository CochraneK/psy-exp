// --- 10 block-design patterns: 4x4 row-major 0/1, left-right symmetric, complexity rising ---
const R={ '00':[0,0,0,0],'01':[0,1,1,0],'10':[1,0,0,1],'11':[1,1,1,1] };
const pat=codes=>codes.reduce((a,c)=>a.concat(R[c]),[]);
const blocks=[
pat('00 01 01 00'.split(' ')),
pat('01 01 01 01'.split(' ')),
pat('00 11 11 00'.split(' ')),
pat('01 10 10 01'.split(' ')),
pat('10 01 01 10'.split(' ')),
pat('11 10 10 11'.split(' ')),
pat('01 11 10 01'.split(' ')),
pat('10 11 11 10'.split(' ')),
pat('11 01 10 11'.split(' ')),
pat('10 11 01 10'.split(' '))
];

// --- wrap each scene into a standalone SVG -> data URI ---
function svgEl(inner){
  return '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 200 150" width="200" height="150" '+
    'style="background:#ffffff"><g fill="none" stroke="#1e293b" stroke-width="3" stroke-linecap="round" '+
    'stroke-linejoin="round">'+inner+'</g></svg>';
}
const svgUri=inner=>'data:image/svg+xml;charset=utf-8,'+encodeURIComponent(svgEl(inner));

const picture=scenes.map(s=>svgUri(s.svg));
// NOTE: expected picture answers (s.a) intentionally stay OUT of the client
// module — the page is open-ended (no auto-scoring of pictures). The research
// scoring reference remains tools/bwais-scenes.cjs (and the dev preview).

